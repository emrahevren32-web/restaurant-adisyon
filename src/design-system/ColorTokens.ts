export const createColorVariableName = (value: string) => (
  value
    .trim()
    .toLocaleLowerCase('en-US')
    .replace(/^#/, 'hex-')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
)

export const getColorToken = (group: ColorTokenGroup, shade: ColorShade) => COLOR_TOKENS[group][shade]
